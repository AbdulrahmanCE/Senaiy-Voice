def load_prompt() -> str:
    """Compose the system prompt.

    Order matters for model attention/recency: put tools FIRST so the persona,
    length, and dialect rules are the freshest content the model sees before
    each reply. End with a one-line reminder of the most-violated rules.
    """
    base = PROMPT_PATH.read_text(encoding="utf-8")
    parts: list[str] = []
    if TOOLS_PROMPT_PATH.exists():
        tools = TOOLS_PROMPT_PATH.read_text(encoding="utf-8").strip()
        if tools:
            parts.append(tools)
    parts.append(base)
    # Tail reminder — sits at the very end of the system prompt, freshest in
    # the model's context window.
    parts.append(
        "\nREMINDER (apply to every reply, especially the FIRST reply of the call):\n"
        "- Length: 5 to 9 sentences typical, never just a 1-word greeting like 'حياك الله!'.\n"
        "- Always end with an open question (unless the user is saying goodbye).\n"
        "- For ERP actions: call the tool BEFORE confirming. No fake confirmations.\n"
    )
    return "\n\n".join(parts) + "\n"


