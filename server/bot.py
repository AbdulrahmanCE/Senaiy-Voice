async def save_audio_file(audio: bytes, filename: str, sample_rate: int, num_channels: int):
    """Save audio data to a WAV file."""
    if len(audio) > 0:
        with io.BytesIO() as buffer:
            with wave.open(buffer, "wb") as wf:
                wf.setsampwidth(2)
                wf.setnchannels(num_channels)
                wf.setframerate(sample_rate)
                wf.writeframes(audio)
            async with aiofiles.open(filename, "wb") as file:
                await file.write(buffer.getvalue())
        logger.info(f"Audio saved to {filename}")



async def get_call_info(call_sid: str) -> dict:
    """Fetch call information from Twilio REST API using aiohttp.

    Args:
        call_sid: The Twilio call SID

    Returns:
        Dictionary containing call information including from_number, to_number, status, etc.
    """
    account_sid = os.getenv("TWILIO_ACCOUNT_SID")
    auth_token = os.getenv("TWILIO_AUTH_TOKEN")

    if not account_sid or not auth_token:
        logger.warning("Missing Twilio credentials, cannot fetch call info")
        return {}

    url = f"https://api.twilio.com/2010-04-01/Accounts/{account_sid}/Calls/{call_sid}.json"

    try:
        # Use HTTP Basic Auth with aiohttp
        auth = aiohttp.BasicAuth(account_sid, auth_token)

        async with aiohttp.ClientSession() as session:
            async with session.get(url, auth=auth) as response:
                if response.status != 200:
                    error_text = await response.text()
                    logger.error(f"Twilio API error ({response.status}): {error_text}")
                    return {}

                data = await response.json()

                call_info = {
                    "from_number": data.get("from"),
                    "to_number": data.get("to"),
                }

                return call_info

    except Exception as e:
        logger.error(f"Error fetching call info from Twilio: {e}")
        return {}



async def run_bot(transport: BaseTransport, call_metadata: dict | None = None):
    """Main bot logic."""
    logger.info("Starting bot")
    call_metadata = call_metadata or {}
    transport_kind = "twilio" if isinstance(transport, FastAPIWebsocketTransport) else "webrtc"
    call_id = _db.start_call(
        transport=transport_kind,
        from_identifier=call_metadata.get("from_number"),
        to_identifier=call_metadata.get("to_number"),
    )
    recording_path_holder = {"path": None}

    # ─── Provider selection ──────────────────────────────────────────────
    # Switch any of LLM / STT / TTS provider via env. Defaults match the
    # current production config (Gemini + Deepgram + ElevenLabs Turbo).
    stt_provider = (os.getenv("STT_PROVIDER", "deepgram") or "deepgram").lower()
    tts_provider = (os.getenv("TTS_PROVIDER", "elevenlabs") or "elevenlabs").lower()
    llm_provider = (os.getenv("LLM_PROVIDER", "gemini") or "gemini").lower()
    logger.info(f"Providers — LLM:{llm_provider}  STT:{stt_provider}  TTS:{tts_provider}")

    # ─── Speech-to-Text ──────────────────────────────────────────────────
    if stt_provider == "deepgram":
        # nova-3 supports Arabic + multilingual; older nova-2 does NOT support Arabic.
        # STT_LANGUAGE=multi enables Arabic+English code-switching; "ar" locks to Arabic.
        stt = DeepgramSTTService(
            api_key=os.getenv("DEEPGRAM_API_KEY"),
            live_options=LiveOptions(
                model=os.getenv("DEEPGRAM_MODEL", "nova-3"),
                language=os.getenv("STT_LANGUAGE", "multi"),
                smart_format=True,
                punctuate=True,
                interim_results=True,
                endpointing=300,
            ),
        )
    elif stt_provider == "soniox":
        stt = SonioxSTTService(
            api_key=os.getenv("SONIOX_API_KEY"),
            settings=SonioxSTTService.Settings(
                language_hints=[Language.AR, Language.EN],
                language_hints_strict=True,
            ),
        )
    else:  # openai / whisper
        stt = OpenAISTTService(
            api_key=os.getenv("OPENAI_API_KEY"),
            language=Language(os.getenv("STT_LANGUAGE", "ar")),
        )

    # ─── Text-to-Speech ──────────────────────────────────────────────────
    aiohttp_session = aiohttp.ClientSession()
    if tts_provider == "openai":
        tts = OpenAITTSService(
            api_key=os.getenv("OPENAI_API_KEY"),
            settings=OpenAITTSService.Settings(
                voice=os.getenv("OPENAI_VOICE_ID", "alloy"),
                speed=float(os.getenv("TTS_SPEED", "1.0")),
            ),
        )
    else:  # elevenlabs
        _eleven_model = os.getenv("ELEVENLABS_MODEL", "eleven_turbo_v2_5")
        tts = ElevenLabsHttpTTSService(
            api_key=os.getenv("ELEVENLABS_API_KEY"),
            aiohttp_session=aiohttp_session,
            settings=ElevenLabsHttpTTSService.Settings(
                voice=os.getenv("ELEVENLABS_VOICE_ID"),
                model=_eleven_model,
                speed=float(os.getenv("TTS_SPEED", "1.0")),
            ),
        )
        # eleven_v3 rejects requests that include previous_text or next_text
        # params. Other models support them. Patch only when on v3.
        if _eleven_model == "eleven_v3":
            _no_continuity = property(lambda self: "", lambda self, v: None)
            type(tts)._previous_text = _no_continuity
            try:
                type(tts)._next_text = _no_continuity
            except Exception:
                pass
            logger.info("ElevenLabs eleven_v3 detected — disabling previous_text/next_text continuity")

    # ─── LLM ─────────────────────────────────────────────────────────────
    _llm_settings_kwargs = {
        "system_instruction": load_prompt(),
    }
    if os.getenv("LLM_MAX_TOKENS"):
        _llm_settings_kwargs["max_tokens"] = int(os.getenv("LLM_MAX_TOKENS"))
    if os.getenv("LLM_TEMPERATURE"):
        _llm_settings_kwargs["temperature"] = float(os.getenv("LLM_TEMPERATURE"))

    if llm_provider == "openai":
        _llm_settings_kwargs["model"] = os.getenv("LLM_MODEL", "gpt-4o")
        llm = OpenAILLMService(
            api_key=os.getenv("OPENAI_API_KEY"),
            settings=OpenAILLMService.Settings(**_llm_settings_kwargs),
        )
    else:  # gemini
        _llm_settings_kwargs["model"] = os.getenv("LLM_MODEL", "gemini-2.5-flash")
        llm = GoogleLLMService(
            api_key=os.getenv("GOOGLE_AI_API_KEY"),
            settings=GoogleLLMService.Settings(**_llm_settings_kwargs),
        )

    # Connect any enabled MCP servers and register their tools with the LLM.
    from pipecat.adapters.schemas.tools_schema import ToolsSchema
    mcp_clients = []
    all_tool_schemas = []

    async def _maybe_refresh_oauth(server: dict) -> dict:
        """If the OAuth token is missing or expired soon, refresh it. Returns updated server dict."""
        import datetime as _dt
        if not server.get("oauth_refresh_token") or not server.get("oauth_token_endpoint"):
            return server
        expires = server.get("oauth_token_expires_at")
        if expires:
            try:
                exp_dt = _dt.datetime.fromisoformat(expires)
                # Refresh if less than 5 minutes left
                if exp_dt - _dt.datetime.now(_dt.timezone.utc) > _dt.timedelta(minutes=5):
                    return server
            except Exception:
                pass
        body = {
            "grant_type": "refresh_token",
            "refresh_token": server["oauth_refresh_token"],
            "client_id": server["oauth_client_id"],
        }
        if server.get("oauth_client_secret"):
            body["client_secret"] = server["oauth_client_secret"]
        try:
            async with aiohttp.ClientSession() as s:
                async with s.post(server["oauth_token_endpoint"], data=body,
                                  headers={"Accept": "application/json"},
                                  timeout=aiohttp.ClientTimeout(total=15)) as r:
                    if r.status >= 400:
                        logger.warning(f"OAuth refresh failed for {server['name']}: HTTP {r.status}")
                        return server
                    import json as _json
                    tok = _json.loads(await r.text())
            new_expires = None
            if tok.get("expires_in"):
                new_expires = (_dt.datetime.now(_dt.timezone.utc)
                               + _dt.timedelta(seconds=int(tok["expires_in"]))).isoformat()
            _db.update_mcp_fields(
                server["id"],
                oauth_access_token=tok.get("access_token"),
                oauth_refresh_token=tok.get("refresh_token", server["oauth_refresh_token"]),
                oauth_token_expires_at=new_expires,
                auth_header_value=f"Bearer {tok.get('access_token')}",
            )
            logger.info(f"🔑 Refreshed OAuth token for {server['name']}")
            return _db.get_mcp_server(server["id"])
        except Exception as e:
            logger.warning(f"OAuth refresh exception for {server['name']}: {e}")
            return server

    for server in _db.list_mcp_servers(only_enabled=True):
        server = await _maybe_refresh_oauth(server)
        try:
            from pipecat.services.mcp_service import MCPClient
            from mcp.client.session_group import StreamableHttpParameters, SseServerParameters
            from mcp.client.stdio import StdioServerParameters

            headers: dict[str, str] = {}
            if server.get("auth_header_name") and server.get("auth_header_value"):
                headers[server["auth_header_name"]] = server["auth_header_value"]

            t = server.get("transport") or "streamable_http"
            if t == "streamable_http":
                params = StreamableHttpParameters(url=server["url"], headers=headers or None)
            elif t == "sse":
                params = SseServerParameters(url=server["url"], headers=headers or None)
            elif t == "stdio":
                # url is treated as the command to spawn for stdio transport
                cmd, *args = server["url"].split()
                params = StdioServerParameters(command=cmd, args=args)
            else:
                logger.warning(f"MCP server {server['name']}: unknown transport '{t}', skipping")
                _db.update_mcp_status(server["id"], f"unknown transport: {t}")
                continue

            tools_filter = None
            if server.get("tools_filter"):
                tools_filter = [t.strip() for t in server["tools_filter"].split(",") if t.strip()]

            client = MCPClient(server_params=params, tools_filter=tools_filter)
            try:
                await client.start()  # required before register_tools / get_tools_schema
                schema = await client.register_tools(llm)
            except BaseException as e:
                # MCP errors come wrapped in TaskGroup/ExceptionGroup; catch BaseException
                # so 401s and similar don't kill the whole session (bot must still talk).
                logger.error(f"❌ MCP server {server.get('name')} unreachable: {type(e).__name__}: {str(e)[:300]}")
                _db.update_mcp_status(server["id"], f"error: {type(e).__name__}: {str(e)[:300]}")
                try:
                    await client.cleanup()
                except Exception:
                    pass
                # Hint about expired OAuth tokens
                if "401" in str(e) or "UNAUTHORIZED" in str(e).upper():
                    logger.warning(f"   ↳ Likely an expired OAuth token. Open the admin and click 'Refresh token' for {server['name']}.")
                continue
            mcp_clients.append(client)
            tool_names = [t.name for t in (schema.standard_tools or [])]
            all_tool_schemas.extend(schema.standard_tools or [])
            _db.update_mcp_status(server["id"], f"bot session: registered {len(tool_names)} tools")
            logger.info(f"✅ MCP server {server['name']} connected. Tools registered ({len(tool_names)}): {tool_names}")
        except Exception as e:
            logger.error(f"❌ MCP server {server.get('name')} failed: {type(e).__name__}: {e}")
            _db.update_mcp_status(server["id"], f"error: {type(e).__name__}: {e}")

    # Log every LLM function call for debugging
    @llm.event_handler("on_function_calls_started")
    async def _on_fc_started(service, function_calls):
        for fc in function_calls:
            logger.info(f"🔧 LLM TOOL CALL → {fc.function_name}({fc.arguments})")

    # Log when tool result comes back, and rewrite CANCELLED results so the
    # LLM doesn't mistake them for a technical failure. Pipecat marks tools
    # cancelled when the user interrupts during the bot's reply — recoverable
    # by calling the same tool again with the same args.
    from pipecat.frames.frames import FunctionCallResultFrame
    _orig_push_frame = llm.push_frame

    async def _logged_push_frame(frame, *a, **kw):
        if isinstance(frame, FunctionCallResultFrame):
            res_preview = str(frame.result)[:300] if frame.result is not None else "None"
            logger.info(f"🔧 LLM TOOL RESULT ← {frame.function_name}: {res_preview}")
            # Rewrite CANCELLED → instruction the LLM can act on
            res_str = str(frame.result) if frame.result is not None else ""
            if res_str.strip() in ("CANCELLED", "'CANCELLED'", '"CANCELLED"'):
                logger.warning(
                    f"   ↳ Tool {frame.function_name} was CANCELLED by user interruption — "
                    f"rewriting result to nudge the LLM to retry silently"
                )
                frame.result = (
                    "TOOL_CANCELLED_BY_USER_INTERRUPTION: This is NOT a technical "
                    "failure. The user spoke before your previous reply finished, "
                    "which cancelled this tool. Call the SAME tool again with the "
                    "SAME arguments, and do it SILENTLY (no acknowledgement before "
                    "the call). Do not apologize. Do not say there was a technical "
                    "issue. Just retry."
                )
        return await _orig_push_frame(frame, *a, **kw)
    llm.push_frame = _logged_push_frame



    context = LLMContext()
    if all_tool_schemas:
        merged = ToolsSchema(standard_tools=all_tool_schemas)
        context.set_tools(merged)
        logger.info(f"📋 LLMContext: {len(all_tool_schemas)} tool schemas attached → OpenAI will see them in every request")

    user_aggregator, assistant_aggregator = LLMContextAggregatorPair(
        context,
        user_params=LLMUserAggregatorParams(
            vad_analyzer=SileroVADAnalyzer(params=VADParams(stop_secs=float(os.getenv("VAD_STOP_SECS", "0.25")))),
            user_turn_strategies=UserTurnStrategies(
                start=default_user_turn_start_strategies(),
                stop=[SpeechTimeoutUserTurnStopStrategy(user_speech_timeout=float(os.getenv("SPEECH_TIMEOUT_SECS", "0.45")))],
            ),
        ),
    )


    # Audio recording
    audio_buffer = AudioBufferProcessor()



    # Pipeline - assembled from reusable components
    pipeline = Pipeline([
        transport.input(),

        stt,

        user_aggregator,

        llm,

        tts,

        
        transport.output(),

        audio_buffer,

        assistant_aggregator,

    ])


    task = PipelineTask(
        pipeline,
        params=PipelineParams(
            enable_metrics=True,
            enable_usage_metrics=True,
            audio_in_sample_rate=16000,
            audio_out_sample_rate=16000,
        ),
        observers=[
            WhiskerObserver(pipeline),
            TailObserver(),
        ],
    )

    @transport.event_handler("on_client_connected")
    async def on_client_connected(transport, client):
        logger.info("Client connected")
        # Start recording audio
        await audio_buffer.start_recording()
        # Fixed Saudi greeting from Senaiy — same words every call/session
        greeting = "هلا والله! أنا سيناي، المساعد الذكي لشركة سولف فاست. وش تحب تعرف؟"
        context.add_message({"role": "assistant", "content": greeting})
        await task.queue_frames([TTSSpeakFrame(greeting)])

    @transport.event_handler("on_client_disconnected")
    async def on_client_disconnected(transport, client):
        logger.info("Client disconnected")
        _db.end_call(call_id, recording_path=recording_path_holder["path"])
        await task.cancel()


    @user_aggregator.event_handler("on_user_turn_stopped")
    async def on_user_turn_stopped(aggregator, strategy, message: UserTurnStoppedMessage):
        timestamp = f"[{message.timestamp}] " if message.timestamp else ""
        line = f"{timestamp}user: {message.content}"
        logger.info(f"Transcript: {line}")
        _db.add_transcript(call_id, "user", message.content, timestamp=str(message.timestamp) if message.timestamp else None)

    @assistant_aggregator.event_handler("on_assistant_turn_stopped")
    async def on_assistant_turn_stopped(aggregator, message: AssistantTurnStoppedMessage):
        timestamp = f"[{message.timestamp}] " if message.timestamp else ""
        line = f"{timestamp}assistant: {message.content}"
        logger.info(f"Transcript: {line}")
        if message.content:
            _db.add_transcript(call_id, "assistant", message.content, timestamp=str(message.timestamp) if message.timestamp else None)


    @audio_buffer.event_handler("on_audio_data")
    async def on_audio_data(buffer, audio, sample_rate, num_channels):
        timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
        filename = str(RECORDINGS_DIR / f"call_{call_id}_{timestamp}.wav")
        await save_audio_file(audio, filename, sample_rate, num_channels)
        recording_path_holder["path"] = filename


    runner = PipelineRunner(handle_sigint=False)

    try:
        await runner.run(task)
    finally:
        for c in mcp_clients:
            try:
                await c.cleanup()
            except Exception as e:
                logger.warning(f"MCP cleanup error: {e}")


async def bot(runner_args: RunnerArguments):
    """Main bot entry point."""

    transport = None
    call_metadata: dict = {}

    match runner_args:
        case SmallWebRTCRunnerArguments():
            webrtc_connection: SmallWebRTCConnection = runner_args.webrtc_connection

            transport = SmallWebRTCTransport(
                webrtc_connection=webrtc_connection,
                params=TransportParams(
                    audio_in_enabled=True,
                    audio_out_enabled=True,
                ),
            )
        case WebSocketRunnerArguments():
            # Parse Twilio websocket and fetch call information
            _, call_data = await parse_telephony_websocket(runner_args.websocket)

            # Fetch call information from Twilio REST API
            # With the call information, you can make a request to your API to get the user's information
            # and inject that information into your bot's configuration.
            call_info = await get_call_info(call_data["call_id"])
            if call_info:
                logger.info(f"Call from: {call_info.get('from_number')} to: {call_info.get('to_number')}")
                call_metadata = call_info

            serializer = TwilioFrameSerializer(
                stream_sid=call_data["stream_id"],
                call_sid=call_data["call_id"],
                account_sid=os.getenv("TWILIO_ACCOUNT_SID", ""),
                auth_token=os.getenv("TWILIO_AUTH_TOKEN", ""),
            )

            transport = FastAPIWebsocketTransport(
                websocket=runner_args.websocket,
                params=FastAPIWebsocketParams(
                    audio_in_enabled=True,
                    audio_out_enabled=True,
                    add_wav_header=False,
                    serializer=serializer,
                ),
            )
        case _:
            logger.error(f"Unsupported runner arguments type: {type(runner_args)}")
            return

    await run_bot(transport, call_metadata=call_metadata)


